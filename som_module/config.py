# -*- coding: utf-8 -*-
"""
som_module/config.py
====================
所有可调节的 SOM 超参数与配置项集中在此。
修改此文件可直接影响 SOM 算法行为，无需改动主代码区。
"""

# ──────────────────────────────────────────────────────────────────────────────
# 文本嵌入模型
# ──────────────────────────────────────────────────────────────────────────────

# 用于将设计选项文本编码为向量的 sentence-transformers 模型名称
# 可替换为其他中文/多语言模型，例如:
#   "paraphrase-multilingual-MiniLM-L12-v2"
#   "shibing624/text2vec-base-chinese-paraphrase"
TEXT_MODEL_NAME = "shibing624/text2vec-base-chinese"

# ──────────────────────────────────────────────────────────────────────────────
# 多模态嵌入权重 (所有权重之和应为 1.0)
# ──────────────────────────────────────────────────────────────────────────────

# NLP 语义相似度权重 (来自 TEXT_MODEL_NAME 编码的文本向量)
WEIGHT_NLP = 0.35

# 共现关系权重 (同一次生成运行中一起出现的选项)
WEIGHT_CO_OCCURRENCE = 0.25

# 类别 (group/category) 权重 (bg_style / chart_type 等)
WEIGHT_CATEGORY = 0.20

# 层级 (bottom/middle/top) 权重
WEIGHT_LAYER = 0.10

# 图结构权重 (PageRank + 度中心性)
WEIGHT_GRAPH = 0.10

# ──────────────────────────────────────────────────────────────────────────────
# MiniSom 超参数
# ──────────────────────────────────────────────────────────────────────────────

# SOM 网格尺寸 = ceil(sqrt(元素数量)) + GRID_SIZE_PADDING
# 增大 GRID_SIZE_PADDING 可使网格更稀疏，减小则更紧凑
GRID_SIZE_PADDING = 5

# 邻域半径 (sigma)，控制相邻神经元的影响范围
# 值越大，训练初期的"涟漪效应"越强
SOM_SIGMA = 1.2

# 学习率，控制每次更新的步长
# 值越大收敛越快但可能不稳定，值越小收敛慢但更精准
SOM_LEARNING_RATE = 0.5

# SOM 拓扑结构: "hexagonal" (六角形，邻域更自然) 或 "rectangular"
SOM_TOPOLOGY = "hexagonal"

# 随机种子，设置为 None 则每次训练结果不同
SOM_RANDOM_SEED = 42

# 训练迭代次数，越大结果越稳定但耗时越长
SOM_TRAINING_ITERATIONS = 5000

# 权重初始化方式: "pca" (PCA 初始化，推荐) 或 "random"
SOM_INIT_METHOD = "pca"

# ──────────────────────────────────────────────────────────────────────────────
# 链接过滤参数
# ──────────────────────────────────────────────────────────────────────────────

# 跨层链接的最小提升度 (Lift)，低于此值的跨层关联将被过滤
# 提升度 = P(A,B) / (P(A) * P(B))，> 1 表示正相关
LINK_MIN_LIFT = 1.2

# ──────────────────────────────────────────────────────────────────────────────
# 层级顺序 (影响排序和 one-hot 编码顺序)
# ──────────────────────────────────────────────────────────────────────────────

LAYER_ORDER = ["bottom_layer", "middle_layer", "top_layer"]

LAYER_PRIORITY = {
    "bottom_layer": 1,
    "middle_layer": 2,
    "top_layer": 3,
    "title_layer": 4,
    "title_scheme": 4,
}

# ──────────────────────────────────────────────────────────────────────────────
# 元素分配算法
# ──────────────────────────────────────────────────────────────────────────────

# 元素到网格节点的分配方式:
#   "hungarian" — 匈牙利算法（线性和分配），每个元素独占一个节点（推荐）
#   "bmu"       — 标准最佳匹配单元（BMU/winner），多个元素可堆叠到同一节点
ASSIGN_METHOD = "hungarian"

# ──────────────────────────────────────────────────────────────────────────────
# 调试 / 输出配置
# ──────────────────────────────────────────────────────────────────────────────

# 是否在训练时打印详细进度
VERBOSE = True
